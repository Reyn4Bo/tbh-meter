// Stage -> blue-chest box, the chest's true identity. Lives in shared/ because BOTH the main
// process (the cooldown tracker keys cooldowns by box) and the renderer (cards + route picker)
// must derive a box from a stageKey. Built from the synced game data (stages.json) — the same
// source the renderer's game-data.ts reads, so the two never drift.
//
// Why box, not stage: many stages drop the SAME box (the in-game "Stage Boss Box LvNN"), and the
// same box can span difficulties (e.g. Lv65 drops in both Hell and Torment). The box IS the chest
// level, so keying a cooldown by box — not stage — is what makes "one cooldown per chest level,
// independent of stage" correct (the 6 duplicate Lv80 cards collapse to one).

import stagesData from "./data/stages.json";
import itemsMinData from "./data/items-min.json";
import { formatStageCode } from "./stage-code.js";

interface StageRecord {
  key: number;
  act: number;
  stageNo: number;
  bossDrop?: { itemKey: number | null; rate: number | null } | null;
  monsterDrop?: { itemKey: number | null; rate: number | null } | null;
}

// itemKey -> display name, e.g. "920801" -> "Stage Boss Box Lv80" (generated by sync-data).
const itemNameMap = itemsMinData as Record<string, string>;

// A blue (stage-boss) box is a 920xxx STAGEBOX. 910xxx = common (gray), 930xxx = act-boss.
// Game 1.3.2 added 925xxx "Contaminated Stage Box (<difficulty>) - N" (one per PLAGUE stage, its own
// 360s cooldown and a "- N" suffix that is NOT a chest level): a different tier, so it stays OUT of the
// blue range — otherwise boxLevel() reads N as the level and the route picker gains 60 bogus chips.
const BLUE_BOX_MIN = 920000;
const BLUE_BOX_MAX = 925000;

/** True when `boxKey` is a blue (stage-boss) box (920xxx, below the contaminated tier). */
export function isBlueBox(boxKey: number | null | undefined): boolean {
  return boxKey != null && boxKey >= BLUE_BOX_MIN && boxKey < BLUE_BOX_MAX;
}

// 925xxx: the Plaguelands stage-boss box — ONE box per plague stage ("- N" = the stage number), so
// keying its cooldown by box is per-stage. Its game DropCooldown is 360 vs the blue box's 300.
const CONTAM_BOX_MIN = 925000;
const CONTAM_BOX_MAX = 926000;

/** True when `boxKey` is a contaminated stage box (925xxx, a Plaguelands stage boss's chest). */
export function isContaminatedBox(boxKey: number | null | undefined): boolean {
  return boxKey != null && boxKey >= CONTAM_BOX_MIN && boxKey < CONTAM_BOX_MAX;
}

/** True for every box the cooldown tracker follows: blue (920xxx) + contaminated (925xxx). */
export function isTrackedBox(boxKey: number | null | undefined): boolean {
  return isBlueBox(boxKey) || isContaminatedBox(boxKey);
}

// stageKey -> its boss-drop box key (920 blue / 925 contaminated / 930 act-boss / 935 contaminated
// act-boss / 941 event), absent when the stage has no boss drop. Same for the mob-drop box (910
// common / 915 contaminated common / 940 event).
const stageToBox = new Map<number, number>();
const stageToMonsterBox = new Map<number, number>();
const stageCodes = new Map<number, string>();
for (const s of stagesData as StageRecord[]) {
  stageCodes.set(s.key, formatStageCode(s.act, s.stageNo));
  const box = s.bossDrop?.itemKey;
  if (box != null) stageToBox.set(s.key, box);
  const mobBox = s.monsterDrop?.itemKey;
  if (mobBox != null) stageToMonsterBox.set(s.key, mobBox);
}

/** The boss-drop box key a stage drops (stage.bossDrop.itemKey), or null if none. Generic: may be
 *  a blue box (920xxx) or an act-boss box (930xxx) — callers that only want blue gate with
 *  `isBlueBox`. */
export function bossBoxForStage(stageKey: number | null | undefined): number | null {
  if (stageKey == null) return null;
  return stageToBox.get(stageKey) ?? null;
}

/** Compact stage code for a stage key ("3-9", "P-20"), or null when unmapped. The main process's
 *  copy of the renderer's game-data stageCode (main can't import renderer code). */
export function stageCodeForKey(stageKey: number): string | null {
  return stageCodes.get(stageKey) ?? null;
}

// Box families (key / 1000) each EMonsterLogType tier can drop: Monster(0) / Boss(1) / ActBoss(2).
const TIER_FAMILIES: Record<number, readonly number[]> = {
  0: [910, 915, 940],
  1: [920, 925, 941],
  2: [930, 935],
};

/**
 * The exact box a drop was, from the stage it dropped on. The reader can't see the box variant
 * (GetBoxLog only carries the TIER), so it emits a canonical key per tier (910011 / 920001 /
 * 930101) — on a Plaguelands stage that made a contaminated box look blue. A stage drops exactly
 * one box per tier (stages.json), so the stage resolves it. Kept as `rawBox` when the stage is
 * unknown or its box isn't of the drop's tier (never invent a box the tier can't be).
 */
export function refineDropBox(stageKey: number | null | undefined, monsterType: number, rawBox: number): number {
  if (stageKey == null) return rawBox;
  const box = monsterType === 0 ? stageToMonsterBox.get(stageKey) : stageToBox.get(stageKey);
  if (box == null) return rawBox;
  return TIER_FAMILIES[monsterType]?.includes(Math.floor(box / 1000)) ? box : rawBox;
}

/** Chest level parsed from the box's display name ("Stage Boss Box Lv80" -> 80, "...Box 4" -> 4).
 *  Null when the name is unmapped or carries no trailing number. The single source for the level
 *  shown on a card and spoken in the OS "ready" notification. */
export function boxLevel(boxKey: number | null | undefined): number | null {
  if (boxKey == null) return null;
  const m = itemNameMap[String(boxKey)]?.match(/(\d+)\s*$/);
  return m ? Number(m[1]) : null;
}

// The distinct blue boxes (chest levels), each with its parsed level, sorted by level ASC — the
// route picker's universe (one chip per level). Built once from the stages that drop a blue box.
const BLUE_BOXES: { boxKey: number; level: number | null }[] = (() => {
  const seen = new Set<number>();
  const out: { boxKey: number; level: number | null }[] = [];
  for (const box of stageToBox.values()) {
    if (!isBlueBox(box) || seen.has(box)) continue;
    seen.add(box);
    out.push({ boxKey: box, level: boxLevel(box) });
  }
  return out.sort((a, b) => (a.level ?? 0) - (b.level ?? 0));
})();

/** Every blue-chest box (chest level) the player can pin to a route, sorted by level. */
export function blueBoxes(): { boxKey: number; level: number | null }[] {
  return BLUE_BOXES;
}
